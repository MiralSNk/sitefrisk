// Пакет ssrf обеспечивает защиту от подделки запросов на стороне сервера.
//
// Сканер отправляет HTTP-запросы от имени пользовательских URL-адресов, что
// делает его естественным вектором для SSRF-атак: злоумышленник может направить его на внутренние
// сервисы (например, на облачные метаданные по адресу 169.254.169.254, внутренние базы данных
// или панели администрирования в локальной сети).
//
// Пакет предоставляет примитивы:
//
//   - ResolveAndCheck разрешает хост и отклоняет его, если какой-либо из разрешённых IP-адресов
//     попадает в запрещённый диапазон (петлевой, частный, локальный и т.д.).
//   - SafeClient возвращает объект http.Client, который не переходит по редиректам
//     автоматически, поэтому можно проверить каждый переход.
//   - SafeGet выполняет GET-запрос, проверяя каждый переход по редиректу с помощью
//     ResolveAndCheck, прежде чем перейти по нему.
//   - Устойчив к перепривязке DNS: проверка IP и открытие TCP-соединения
//     используют один и тот же резолв (см. safeDialContext), поэтому
//     между "проверили" и "подключились" не остаётся окна для повторного
//     DNS-запроса с другим ответом. При нескольких резолвнутых IP
//     используется только первый из проверенного списка.
//   - Ограничивает набор разрешенных портов.
//
// SafeDo — это общая точка входа: она принимает любой *http.Request без
// тела запроса и выполняет проверку на SSRF при каждом переходе по редиректу. SafeGet — это тонкая
// оболочка для стандартного GET-запроса.
//
// Тела запросов не поддерживаются: SafeDo возвращает ErrBodyNotSupported, если
// в запросе есть непустое тело. Повторное использование тел запросов при редиректах — это
// известный вектор утечки учетных данных, который не подходит для сканеров, работающих с запросами HEAD/GET.
//
// Конфиденциальные заголовки (Authorization, WWW-Authenticate, Cookie, Cookie2)
// удаляются при любом межхостовом редиректе, что соответствует поведению стандартного
// http.Клиент.
