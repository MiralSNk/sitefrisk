// Package sanitize очищает собранные Fact.Value перед тем, как они
// уйдут за пределы сканера (например, в AnalyzeRequest ML-сервиса).
//
// Цель — защититься от того, что сканируемая цель кладёт в заголовки
// или другой возвращаемый контент текст, рассчитанный на то, что его
// прочитает не человек, а LLM на другом конце (prompt injection):
// невидимые Unicode-символы, маскирующие текст от визуального ревью,
// управляющие символы, переполнение длины для context-stuffing.
//
// Clean — это defense-in-depth, не доказуемая защита (в отличие от
// ssrf, где множество "запрещённых" IP конечно и перечисляемо — у
// prompt injection через естественный текст конечного списка не
// существует). Финальный барьер — архитектура промпта на стороне
// ML-сервиса (разделение instruction/data), не эта очистка.
